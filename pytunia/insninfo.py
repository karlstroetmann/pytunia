"""
Information about the JVM instructions known to Jasmin: the opcode and
the kind of arguments of every instruction (port of jasmin.InsnInfo).

Argument kinds:
    ""            no arguments
    "i"           an integer (local variable index, byte, short, ...)
    "I"           like "i", but always use the wide form
    "ii", "Ii"    two integers (iinc)
    "constant"    a constant (ldc, ldc_w)
    "bigconstant" a long or double constant (ldc2_w)
    "label"       a branch target
    "class"       a class name
    "field"       a field and its descriptor
    "method"      a method with descriptor
    "interface"   an interface method and the argument count
    "marray"      an array type and the number of dimensions
    "atype"       a primitive array type (newarray)
    "switch"      lookupswitch / tableswitch
"""

from .jas import constants as rc


class InsnInfo(object):
    __slots__ = ("name", "opcode", "args")

    def __init__(self, name, opcode, args):
        self.name = name
        self.opcode = opcode
        self.args = args


_INFO_TABLE = {}


def _add(name, opcode, args):
    _INFO_TABLE[name] = InsnInfo(name, opcode, args)


