def _build_action_table():
    """For every state a list indexed by terminal number, with the result
    of lr_parser.get_action() (linear search for short rows, binary
    search for rows of 20 or more entries)."""
    nterms = max(sym.NAMES) + 1
    table = []
    for row in T.ACTION_TABLE:
        actions = []
        for s in range(nterms):
            actions.append(_get_action(row, s))
        table.append(actions)
    return table


def _get_action(row, s):
    if len(row) < 20:
        for probe in range(0, len(row), 2):
            tag = row[probe]
            if tag == s or tag == -1:
                return row[probe + 1]
        return 0
    first = 0
    last = (len(row) - 1) // 2 - 1     # leave out trailing default entry
    while first <= last:
        probe = (first + last) // 2
        if s == row[probe * 2]:
            return row[probe * 2 + 1]
        elif s > row[probe * 2]:
            first = probe + 1
        else:
            last = probe - 1
    return row[len(row) - 1]


def _build_reduce_table():
    table = []
    for row in T.REDUCE_TABLE:
        gotos = {}
        default = -1
        for probe in range(0, len(row), 2):
            tag = row[probe]
            if tag == -1:
                default = row[probe + 1]
                break
            gotos.setdefault(tag, row[probe + 1])
        table.append((gotos, default))
    return table


_ACTIONS = _build_action_table()
_REDUCE = _build_reduce_table()
_PRODUCTIONS = T.PRODUCTION_TABLE


def _get_reduce(state, s):
    gotos, default = _REDUCE[state]
    return gotos.get(s, default)


class _VirtualParseStack(object):
    """Port of java_cup.runtime.virtual_parse_stack: a stack of parser
    states that shadows the real parse stack during error recovery."""

    def __init__(self, shadowing_stack):
        self.real_stack = shadowing_stack
        self.real_next = 0
        self.vstack = []
        self._get_from_real()

    def _get_from_real(self):
        if self.real_next >= len(self.real_stack):
            return
        sym_ = self.real_stack[len(self.real_stack) - 1 - self.real_next]
        self.real_next += 1
        self.vstack.append(sym_.parse_state)

    def top(self):
        if not self.vstack:
            raise JavaException("java.lang.Exception",
                                "Internal parser error: top() called on "
                                "empty virtual stack")
        return self.vstack[-1]

    def pop(self):
        if not self.vstack:
            raise JavaException("java.lang.Exception",
                                "Internal parser error: pop from empty "
                                "virtual stack")
        self.vstack.pop()
        if not self.vstack:
            self._get_from_real()

    def push(self, state):
        self.vstack.append(state)


