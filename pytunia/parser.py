"""
The Jasmin parser.

The Java version uses an LALR(1) parser generated by Java CUP 0.9 from
the grammar in parser.cup.  This module contains

* a port of the CUP runtime (java_cup.runtime.lr_parser), including its
  error recovery, and
* the semantic actions of the grammar, which call the methods of
  pytunia.classfile.ClassFile.

The parse tables themselves (module parser_tables) were extracted from
the parser generated by CUP, so the Python port accepts exactly the same
language and recovers from syntax errors in the same way.

The grammar (simplified; see parser_tables.RULES for the full list of
productions):

    jas_file      ::= jasmin_header inners fields methods
    jasmin_header ::= [.bytecode] [.source] (.class|.interface) .super
                      .implements* [.signature] [.enclosing]
                      [.deprecated] .annotation* .attribute* .debug*
    inners        ::= (.inner (class|interface) ...)*
    fields        ::= (.field ... | .field ... .end field)*
    methods       ::= (.method access name(desc) statement* .end method)*
    statement     ::= [ instruction | directive | label ] SEP
"""

