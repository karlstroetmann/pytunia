class LRParser(object):
    error_sync_size = 3

    def __init__(self):
        self.stack = []
        self.cur_token = None
        self.lookahead = None
        self.lookahead_pos = 0
        self._done_parsing = False

    # --- to be supplied by subclasses ---------------------------------

    def scan(self):
        raise NotImplementedError

    def do_action(self, act_num, stack):
        raise NotImplementedError

    def report_error(self, message, info):
        raise NotImplementedError

    def report_fatal_error(self, message, info):
        raise NotImplementedError

    # --- runtime ------------------------------------------------------

    def done_parsing(self):
        self._done_parsing = True

    def syntax_error(self, cur_token):
        self.report_error("Syntax error", None)

    def unrecovered_syntax_error(self, cur_token):
        self.report_fatal_error("Couldn't repair and continue parse", None)

    def _reduce(self, prod):
        lhs_sym = self.do_action(prod, self.stack)
        lhs_sym_num, handle_size = _PRODUCTIONS[prod]
        if handle_size:
            del self.stack[-handle_size:]
        lhs_sym.parse_state = _get_reduce(self.stack[-1].parse_state,
                                          lhs_sym_num)
        self.stack.append(lhs_sym)

    def parse(self):
        self.cur_token = self.scan()
        self.stack = [Token(0, parse_state=T.START_STATE)]
        self._done_parsing = False
        stack = self.stack
        while not self._done_parsing:
            act = _ACTIONS[stack[-1].parse_state][self.cur_token.sym]
            if act > 0:
                # shift
                self.cur_token.parse_state = act - 1
                stack.append(self.cur_token)
                self.cur_token = self.scan()
            elif act < 0:
                # reduce
                self._reduce(-act - 1)
            else:
                # syntax error
                self.syntax_error(self.cur_token)
                if not self.error_recovery():
                    self.unrecovered_syntax_error(self.cur_token)
                    self.done_parsing()

    # --- error recovery -----------------------------------------------

    def error_recovery(self):
        if not self._find_recovery_config():
            return False
        self._read_lookahead()
        while True:
            if self._try_parse_ahead():
                break
            if self.lookahead[0].sym == T.EOF_SYM:
                return False
            self._restart_lookahead()
        self._parse_lookahead()
        return True

    def _shift_under_error(self):
        return _ACTIONS[self.stack[-1].parse_state][T.ERROR_SYM] > 0

    def _find_recovery_config(self):
        while not self._shift_under_error():
            self.stack.pop()
            if not self.stack:
                return False
        act = _ACTIONS[self.stack[-1].parse_state][T.ERROR_SYM]
        self.stack.append(Token(T.ERROR_SYM, parse_state=act - 1))
        return True

    def _read_lookahead(self):
        self.lookahead = [None] * self.error_sync_size
        for i in range(self.error_sync_size):
            self.lookahead[i] = self.cur_token
            self.cur_token = self.scan()
        self.lookahead_pos = 0

    def _cur_err_token(self):
        return self.lookahead[self.lookahead_pos]

    def _advance_lookahead(self):
        self.lookahead_pos += 1
        return self.lookahead_pos < self.error_sync_size

    def _restart_lookahead(self):
        for i in range(1, self.error_sync_size):
            self.lookahead[i - 1] = self.lookahead[i]
        self.cur_token = self.scan()
        self.lookahead[self.error_sync_size - 1] = self.cur_token
        self.lookahead_pos = 0

    def _try_parse_ahead(self):
        vstack = _VirtualParseStack(self.stack)
        while True:
            act = _ACTIONS[vstack.top()][self._cur_err_token().sym]
            if act == 0:
                return False
            if act > 0:
                vstack.push(act - 1)
                if not self._advance_lookahead():
                    return True
            else:
                if -act - 1 == T.START_PRODUCTION:
                    return True
                lhs, rhs_size = _PRODUCTIONS[-act - 1]
                for _ in range(rhs_size):
                    vstack.pop()
                vstack.push(_get_reduce(vstack.top(), lhs))

    def _parse_lookahead(self):
        self.lookahead_pos = 0
        stack = self.stack
        while not self._done_parsing:
            tok = self._cur_err_token()
            act = _ACTIONS[stack[-1].parse_state][tok.sym]
            if act > 0:
                tok.parse_state = act - 1
                stack.append(tok)
                if not self._advance_lookahead():
                    # scan next token so we can continue parse
                    self.cur_token = self.scan()
                    return
            elif act < 0:
                self._reduce(-act - 1)
            else:
                self.report_fatal_error("Syntax error", None)
                return


