#!/usr/bin/env python3
"""
Extract the LALR(1) parse tables of the original Jasmin parser.

The Java version of Jasmin uses a parser generated by Java CUP 0.9 from
the grammar in src/jasmin/parser.cup.  The Python port uses the very same
parse tables, so that it accepts exactly the same language and performs
the same error recovery.  This script reads the generated files
src/jasmin/parser.java and src/jasmin/sym.java and writes the modules
pytunia/parser_tables.py and pytunia/sym.py.

usage: python3 extract_tables.py <path to jasmin-2.4/src/jasmin>
"""

import os
import re
import sys
import textwrap


def extract_array(src, name):
    m = re.search(r'%s\s*\[?\]?\s*(?:\[\])*\s*=\s*\{(.*?)\};'
                  % re.escape(name), src, re.S)
    if not m:
        raise SystemExit("cannot find table " + name)
    body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    rows = re.findall(r'\{([^{}]*)\}', body)
    return [tuple(int(x) for x in row.split(',') if x.strip())
            for row in rows]


def format_rows(name, rows, comment):
    lines = ['# ' + comment, '%s = (' % name]
    for i, row in enumerate(rows):
        text = '(%s)' % ', '.join(str(x) for x in row)
        if len(row) == 1:
            text = '(%d,)' % row[0]
        wrapped = textwrap.wrap(text, 70)
        lines.append('    # %d' % i)
        for w in wrapped:
            lines.append('    ' + w)
        lines[-1] += ','
    lines.append(')')
    return '\n'.join(lines) + '\n'


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    srcdir = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    pkg = os.path.join(here, os.pardir, 'pytunia')

    with open(os.path.join(srcdir, 'parser.java')) as f:
        parser = f.read()
    prod = extract_array(parser, '_production_table')
    action = extract_array(parser, '_action_table')
    reduce_ = extract_array(parser, '_reduce_table')
    start_state = int(re.search(r'start_state\(\)\s*\{return (\d+);',
                                parser).group(1))
    start_prod = int(re.search(r'start_production\(\)\s*\{return (\d+);',
                               parser).group(1))
    eof_sym = int(re.search(r'EOF_sym\(\)\s*\{return (\d+);',
                            parser).group(1))
    error_sym = int(re.search(r'error_sym\(\)\s*\{return (\d+);',
                              parser).group(1))
    rules = dict((int(n), r.strip()) for n, r in
                 re.findall(r'case (\d+): // (.*)', parser))

    out = ['"""',
           'Parse tables of the Jasmin parser.',
           '',
           'GENERATED FILE - DO NOT EDIT.  These tables were extracted by',
           'tools/extract_tables.py from the parser that Java CUP 0.9',
           'generated for the grammar of Jasmin 2.4 (src/jasmin/parser.cup).',
           '"""',
           '',
           'START_STATE = %d' % start_state,
           'START_PRODUCTION = %d' % start_prod,
           'EOF_SYM = %d' % eof_sym,
           'ERROR_SYM = %d' % error_sym,
           '',
           '# the productions of the grammar (for documentation and '
           'debugging)',
           'RULES = (']
    for i in range(len(prod)):
        out.append('    %r,  # %d' % (rules.get(i, '?'), i))
    out.append(')')
    out.append('')
    out.append(format_rows('PRODUCTION_TABLE', prod,
                           'for every production: (lhs symbol, rhs length)'))
    out.append(format_rows('ACTION_TABLE', action,
                           'for every state: pairs (terminal, action); '
                           'terminal -1 is the default'))
    out.append(format_rows('REDUCE_TABLE', reduce_,
                           'for every state: pairs (nonterminal, goto '
                           'state); -1 is the default'))
    with open(os.path.join(pkg, 'parser_tables.py'), 'w') as f:
        f.write('\n'.join(out))

    with open(os.path.join(srcdir, 'sym.java')) as f:
        syms = re.findall(r'static final int (\w+) = (\d+);', f.read())
    syms.sort(key=lambda s: int(s[1]))
    out = ['"""',
           'Terminal symbols of the Jasmin grammar.',
           '',
           'GENERATED FILE - DO NOT EDIT (see tools/extract_tables.py).',
           '"""',
           '']
    for name, value in syms:
        out.append('%s = %s' % (name, value))
    out.append('')
    out.append('NAMES = {')
    for name, value in syms:
        out.append('    %s: %r,' % (value, name))
    out.append('}')
    with open(os.path.join(pkg, 'sym.py'), 'w') as f:
        f.write('\n'.join(out) + '\n')
    print("wrote parser_tables.py (%d productions, %d states) and sym.py"
          % (len(prod), len(action)))


if __name__ == '__main__':
    main()
